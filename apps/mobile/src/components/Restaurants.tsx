export interface RestaurantPinData {
  id: string;
  latitude: number;
  longitude: number;
  open: boolean;
  selected: boolean;
}

function RestaurantPin({ id, open }: { id: string; open: boolean }) {
  useLocale();
  return (
    <View testID={`branch-pin-${id}`} style={s.pin}>
      <View style={s.pinShadow} />
      <View
        testID={`branch-pin-drop-${id}`}
        style={[s.pinDrop, { backgroundColor: open ? colors.accent : `${colors.muted}B3` }]}
      />
      <View style={s.pinLogo}>
        <Image
          source={open ? assets.logo : closedLogo}
          style={StyleSheet.absoluteFill}
          contentFit="cover"
        />
      </View>
    </View>
  );
}

export function RestaurantMap({
  pins,
  children,
}: {
  pins: RestaurantPinData[];
  children?: ReactNode;
}) {
  useLocale();
  const [width, setWidth] = useState(mapMetadata.width);
  const height = RESTAURANT_MAP_HEIGHT;
  // The selected restaurant's pin is drawn last, above its neighbours.
  const ordered = [...pins].sort((a, b) => Number(a.selected) - Number(b.selected));
  return (
    <View
      testID="branches-map"
      onLayout={(event) => setWidth(event.nativeEvent.layout.width)}
      style={[s.map, { height }]}
    >
      <View
        style={StyleSheet.absoluteFill}
        accessibilityElementsHidden
        importantForAccessibility="no-hide-descendants"
      >
        <Image
          source={mapImage}
          style={StyleSheet.absoluteFill}
          contentFit="cover"
          transition={0}
        />
        {ordered.map((pin) => {
          const point = coverPoint(
            mapMetadata,
            staticMapPoint(mapMetadata, pin.latitude, pin.longitude),
            width,
            height,
          );
          if (point.x < 0 || point.x > width || point.y < PIN_TIP || point.y > height) return null;
          return (
            <View
              key={pin.id}
              pointerEvents="none"
              style={[s.pinPosition, { left: point.x - PIN / 2, top: point.y - PIN_TIP }]}
            >
              <RestaurantPin id={pin.id} open={pin.open} />
            </View>
          );
        })}
      </View>
      <Pressable
        testID="map-attribution"
        accessibilityRole="link"
        accessibilityLabel={t('Данные карты: участники OpenStreetMap')}
        onPress={() => void Linking.openURL(OSM_COPYRIGHT).catch(() => {})}
        style={s.attribution}
      >
        <Text style={s.attributionText}>{localize(mapMetadata.attribution)}</Text>
      </Pressable>
      {children}
    </View>
  );
}

/** One city for now: the button opens a list with that single, selected item. */
export function CityButton({ city, top }: { city: string; top: number }) {
  useLocale();
  const [open, setOpen] = useState(false);
  return (
    <View style={[s.city, { top }]}>
      <Pressable
        testID="branches-city"
        accessibilityRole="button"
        accessibilityLabel={localize(t('Город: {p0}', { p0: city }))}
        accessibilityState={{ expanded: open }}
        onPress={() => setOpen((value) => !value)}
        style={s.cityButton}
      >
        <Text style={s.cityText}>{localize(city)}</Text>
        <Icon name={open ? 'chevron-up' : 'chevron-down'} size={14} color={colors.muted} />
      </Pressable>
      {open ? (
        <View style={s.cityList}>
          <Pressable
            testID="branches-city-option"
            accessibilityRole="radio"
            accessibilityState={{ selected: true, checked: true }}
            aria-checked
            onPress={() => setOpen(false)}
            style={s.cityOption}
          >
            <Text style={s.cityOptionText}>{localize(city)}</Text>
            <Icon name="checkmark" size={20} color={colors.accent} />
          </Pressable>
        </View>
      ) : null}
    </View>
  );
}

export function RestaurantCard({
  branch,
  address,
  status,
  selected,
  onSelect,
  onOpenMap,
}: {
  branch: Branch;
  address?: string;
  status: RestaurantHoursStatus | null;
  selected: boolean;
  onSelect(): void;
  onOpenMap?: () => void;
}) {
  useLocale();
  const text = status ? hoursStatusText(status) : null;
  return (
    <View style={s.card}>
      <Pressable
        testID={`branch-${branch.id}`}
        accessibilityRole="radio"
        accessibilityState={{ selected, checked: selected }}
        aria-checked={selected}
        onPress={onSelect}
        style={s.selectRow}
      >
        <View style={s.cardText}>
          <Text style={s.name}>{localize(branch.name)}</Text>
          {address ? (
            <Text style={s.address} numberOfLines={1}>
              {localize(address)}
            </Text>
          ) : null}
          <Text testID={`branch-status-${branch.id}`} style={s.status}>
            {localize(
              text ? (
                <>
                  <Text
                    style={[
                      s.statusState,
                      { color: status?.open ? restaurantColors.open : restaurantColors.closed },
                    ]}
                  >
                    {localize(text.state)}
                  </Text>
                  {` · ${text.detail}`}
                </>
              ) : branch.ordering_enabled ? (
                'Приём заказов доступен'
              ) : (
                'Заказы пока недоступны'
              ),
            )}
          </Text>
        </View>
        {selected ? <SelectedCheck /> : null}
      </Pressable>
      {onOpenMap ? (
        <>
          <View style={s.divider} />
          <Pressable
            testID={`branch-map-${branch.id}`}
            accessibilityRole="link"
            accessibilityLabel={localize(t('Открыть {p0} в 2ГИС', { p0: branch.name }))}
            onPress={onOpenMap}
            style={s.mapRow}
          >
            <Text style={s.mapText}>{t('Открыть в 2ГИС')}</Text>
            <View style={s.external}>
              <Icon name="arrow-up" size={15} color={colors.accentText} />
            </View>
          </Pressable>
        </>
      ) : null}
    </View>
  );
}

