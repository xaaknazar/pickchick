export const RESTAURANT_MAP_HEIGHT = 320;
const PIN = 46;
const PIN_TIP_RADIUS = 3;
// A square rotated 45° with three round corners; its fourth, slightly rounded corner
// is the tip. Distance from the top of the pin to the visible end of the tip:
const PIN_TIP = PIN / 2 + (PIN / 2 - PIN_TIP_RADIUS) * Math.SQRT2 + PIN_TIP_RADIUS;
const OSM_COPYRIGHT = 'https://www.openstreetmap.org/copyright';

/** Re-renders on every minute boundary and when the app returns to the foreground. */
export function useMinuteClock(): Date {
  const [now, setNow] = useState(() => new Date());
  useEffect(() => {
    let timer: ReturnType<typeof setTimeout> | undefined;
    const schedule = () => {
      timer = setTimeout(
        () => {
          setNow(new Date());
          schedule();
        },
        60_000 - (Date.now() % 60_000) + 50,
      );
    };
    schedule();
    const subscription = AppState.addEventListener('change', (state) => {
      if (state === 'active') setNow(new Date());
    });
    return () => {
      clearTimeout(timer);
      subscription.remove();
    };
  }, []);
  return now;
}

/** Prefer the installed 2GIS app; the web page is the fallback (and the only option on web). */
export async function openIn2Gis(mapUrl: string): Promise<void> {
  const app = Platform.OS === 'web' ? null : dgisAppUrl(mapUrl);
  if (app) {
    try {
      if (await Linking.canOpenURL(app)) {
        await Linking.openURL(app);
        return;
      }
    } catch {
      // Fall through to the web page.
    }
  }
  await Linking.openURL(mapUrl);
}

// The approved mockup's check: thinner than a filled badge, with round ends.
const checkSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="${colors.accent}" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round"><path d="M5.5 12.5l4.5 4.5L18.5 8"/></svg>`;
