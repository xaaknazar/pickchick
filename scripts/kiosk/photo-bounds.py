"""Visible bounds of the kiosk's bundled cut-out photos (owner 23.11.2026).

The menu cards and the combo hero fit a photo by its visible dish, not by its canvas, so
every dish fills its tile the same way («фото комбо стоят разные»). This writes
apps/kiosk/src/bundled-photo-bounds.ts: for every cut-out (an image with alpha) required in
apps/kiosk/src/assets.ts, its width/height ratio and the box of pixels with alpha >= 64 as
fractions [left, top, right, bottom]. Images without alpha are left out (their backdrop is
part of the photo).

Usage (from the repository root, Pillow with WebP required):
    python3 scripts/kiosk/photo-bounds.py           # rewrite the TypeScript table
    python3 scripts/kiosk/photo-bounds.py --check   # fail if the table is stale
"""

import argparse
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'apps/kiosk/src/assets.ts'
OUT = ROOT / 'apps/kiosk/src/bundled-photo-bounds.ts'


def bounds(path):
    image = Image.open(path)
    if 'A' not in image.getbands():
        return None
    alpha = image.convert('RGBA').getchannel('A').point(lambda v: 255 if v >= 64 else 0)
    box = alpha.getbbox()
    if not box:
        return None
    width, height = image.size
    return (round(width / height, 4), round(box[0] / width, 4), round(box[1] / height, 4),
            round(box[2] / width, 4), round(box[3] / height, 4))


def render():
    sources = sorted(set(re.findall(r"require\('(\.\./assets/[^']+\.(?:png|webp))'\)",
                                    ASSETS.read_text())))
    rows = []
    for source in sources:
        box = bounds(ASSETS.parent / source)
        if box:
            rows.append(f"  [require('{source}'), [{', '.join(str(v) for v in box)}]],")
    return ('// Generated by scripts/kiosk/photo-bounds.py - do not edit by hand.\n'
            '// [width / height, left, top, right, bottom] of the visible pixels (alpha >= 64).\n'
            "import type { PhotoBounds } from './photo-bounds';\n\n"
            'export const bundledPhotoBounds = new Map<number, PhotoBounds>([\n'
            + '\n'.join(rows) + '\n]);\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render()
    if args.check:
        if OUT.read_text() != text:
            sys.exit('bundled-photo-bounds.ts is stale: run scripts/kiosk/photo-bounds.py')
        return
    OUT.write_text(text)


if __name__ == '__main__':
    main()
